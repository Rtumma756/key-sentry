// Remediation guidance per finding + Markdown report builder (masked only).

import type { Finding, ScanMetrics } from "./scan";

export interface RemediationStep {
  title: string;
  detail: string;
  link?: string;
  linkLabel?: string;
}

export function remediationSteps(f: Finding): RemediationStep[] {
  const steps: RemediationStep[] = [
    {
      title: "Revoke the key now",
      detail:
        "A leaked key is live until it is revoked. Treat it as compromised even if it was only exposed briefly.",
      link: f.consoleUrl || undefined,
      linkLabel: f.consoleUrl
        ? `Open ${f.provider} key settings`
        : undefined,
    },
    {
      title: "Rotate in a new key",
      detail:
        "Create a fresh key at the provider, store it in an environment variable or secret manager, and update every service that used the old one.",
    },
    {
      title: "Remove it from git history",
      detail:
        "Deleting the file is not enough — the key stays in history. Rewrite history with git filter-repo or BFG, then force-push and tell collaborators to re-clone.",
    },
    {
      title: "Move secrets out of code",
      detail:
        "Load the key from an environment variable or a secret manager (e.g. Doppler, 1Password, AWS Secrets Manager). Never hardcode keys in source, config, or notebooks.",
    },
    {
      title: "Add the file to .gitignore",
      detail:
        "Add .env, config files with secrets, and credential files to .gitignore so they cannot be committed again.",
    },
    {
      title: "Enable push protection",
      detail:
        "Turn on secret scanning with push protection (GitHub Settings → Code security) so commits containing known key patterns are blocked before they land.",
    },
  ];
  return steps;
}

export function buildMarkdownReport(
  findings: Finding[],
  metrics: ScanMetrics,
  sourceLabel: string,
): string {
  const lines: string[] = [];
  lines.push("# KeySentry scan report");
  lines.push("");
  lines.push(`Source: ${sourceLabel}`);
  lines.push(`Scanned: ${metrics.linesScanned} lines in ${metrics.scanTimeMs} ms`);
  lines.push(`Findings: ${metrics.findingsAfterDedup} (after removing ${metrics.duplicatesRemoved} duplicate${metrics.duplicatesRemoved === 1 ? "" : "s"})`);
  lines.push("");
  if (findings.length === 0) {
    lines.push("No leaked AI API keys found.");
    return lines.join("\n");
  }
  lines.push("## Findings (keys are masked — full values are never shown)");
  lines.push("");
  for (const f of findings) {
    lines.push(`### ${f.provider} — ${f.credType} [${f.severity}]`);
    lines.push(`- Key: \`${f.maskedKey}\``);
    lines.push(`- Location: ${f.source}, line ${f.lineNumber}`);
    lines.push(`- Detected via: ${f.via}`);
    if (f.consoleUrl) lines.push(`- Revoke at: ${f.consoleUrl}`);
    lines.push("");
    lines.push("Remediation checklist:");
    for (const s of remediationSteps(f)) {
      lines.push(`- [ ] ${s.title} — ${s.detail}`);
    }
    lines.push("");
  }
  lines.push("## Metrics");
  lines.push("");
  lines.push(`- By provider: ${Object.entries(metrics.byProvider).map(([k, v]) => `${k} (${v})`).join(", ")}`);
  lines.push(`- By severity: ${Object.entries(metrics.bySeverity).map(([k, v]) => `${k} (${v})`).join(", ")}`);
  lines.push("");
  lines.push("_Generated by KeySentry. Keys are masked in this report._");
  return lines.join("\n");
}
